package cm.gimac.des.pilotage.domain;

import static cm.gimac.des.pilotage.domain.AssertUtils.bigDecimalCompareTo;
import static org.assertj.core.api.Assertions.assertThat;

public class ProjectAsserts {

    /**
     * Asserts that the entity has all properties (fields/relationships) set.
     *
     * @param expected the expected entity
     * @param actual the actual entity
     */
    public static void assertProjectAllPropertiesEquals(Project expected, Project actual) {
        assertProjectAutoGeneratedPropertiesEquals(expected, actual);
        assertProjectAllUpdatablePropertiesEquals(expected, actual);
    }

    /**
     * Asserts that the entity has all updatable properties (fields/relationships) set.
     *
     * @param expected the expected entity
     * @param actual the actual entity
     */
    public static void assertProjectAllUpdatablePropertiesEquals(Project expected, Project actual) {
        assertProjectUpdatableFieldsEquals(expected, actual);
        assertProjectUpdatableRelationshipsEquals(expected, actual);
    }

    /**
     * Asserts that the entity has all the auto generated properties (fields/relationships) set.
     *
     * @param expected the expected entity
     * @param actual the actual entity
     */
    public static void assertProjectAutoGeneratedPropertiesEquals(Project expected, Project actual) {
        assertThat(actual)
            .as("Verify Project auto generated properties")
            .satisfies(a -> assertThat(a.getId()).as("check id").isEqualTo(expected.getId()));
    }

    /**
     * Asserts that the entity has all the updatable fields set.
     *
     * @param expected the expected entity
     * @param actual the actual entity
     */
    public static void assertProjectUpdatableFieldsEquals(Project expected, Project actual) {
        assertThat(actual)
            .as("Verify Project relevant properties")
            .satisfies(a -> assertThat(a.getTitle()).as("check title").isEqualTo(expected.getTitle()))
            .satisfies(a -> assertThat(a.getScope()).as("check scope").isEqualTo(expected.getScope()))
            .satisfies(a -> assertThat(a.getOwnerId()).as("check ownerId").isEqualTo(expected.getOwnerId()))
            .satisfies(a ->
                assertThat(a.getBudget()).as("check budget").usingComparator(bigDecimalCompareTo).isEqualTo(expected.getBudget())
            )
            .satisfies(a -> assertThat(a.getProgress()).as("check progress").isEqualTo(expected.getProgress()))
            .satisfies(a -> assertThat(a.getStartDate()).as("check startDate").isEqualTo(expected.getStartDate()))
            .satisfies(a -> assertThat(a.getTargetDate()).as("check targetDate").isEqualTo(expected.getTargetDate()))
            .satisfies(a ->
                assertThat(a.getExpectedDurationDays())
                    .as("check expectedDurationDays")
                    .usingComparator(bigDecimalCompareTo)
                    .isEqualTo(expected.getExpectedDurationDays())
            )
            .satisfies(a ->
                assertThat(a.getOnTimeProbability())
                    .as("check onTimeProbability")
                    .usingComparator(bigDecimalCompareTo)
                    .isEqualTo(expected.getOnTimeProbability())
            )
            .satisfies(a -> assertThat(a.getCriticalPath()).as("check criticalPath").isEqualTo(expected.getCriticalPath()))
            .satisfies(a -> assertThat(a.getScheduledAt()).as("check scheduledAt").isEqualTo(expected.getScheduledAt()));
    }

    /**
     * Asserts that the entity has all the updatable relationships set.
     *
     * @param expected the expected entity
     * @param actual the actual entity
     */
    public static void assertProjectUpdatableRelationshipsEquals(Project expected, Project actual) {
        assertThat(actual)
            .as("Verify Project relationships")
            .satisfies(a -> assertThat(a.getDependencies()).as("check dependencies").isEqualTo(expected.getDependencies()))
            .satisfies(a -> assertThat(a.getDependents()).as("check dependents").isEqualTo(expected.getDependents()));
    }
}
