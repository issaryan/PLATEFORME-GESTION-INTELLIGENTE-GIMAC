    expect((await parcours.dossier('LIA-2026-027')).statut).toBe('CERTIFIEE')
    await expect(decision.etablirProcesVerbal('LIA-2026-041')).rejects.toEqual(refus('CER_COVERAGE_INCOMPLETE'))
