    await expect(p2.deposerAttestation('LIA-2026-027', 'PCI_DSS', new File(['x'], 'att.png'))).rejects.toEqual(refus('CER_ATTESTATION_FORMAT'))
    await expect(p2.deposerAttestation('LIA-2026-027', 'GSMA', fichier('g.pdf'))).rejects.toEqual(refus('CER_ATTESTATION_NOT_REQUIRED'))
