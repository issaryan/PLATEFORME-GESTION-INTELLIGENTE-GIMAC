    await decision.signerProcesVerbalGimac('LIA-2026-027', 'a')
    expect((await decision.procesVerbal('LIA-2026-027')).etat).toBe('SIGNE_GIMAC')
    await expect(decision.signerProcesVerbalGimac('LIA-2026-027', 'a')).rejects.toEqual(refus('CER_PV_NOT_SIGNABLE'))
