import { afterEach, describe, expect, it, vi } from 'vitest'
import { cleanup, fireEvent, screen, waitFor, within } from '@testing-library/react'
import { ApiError } from '@gimac/socle'
import ComptePage from './ComptePage'
import { LECTEUR, RSSI, SUPER_ADMIN, avec, confirmer, rendrePage, session, signer, simules } from '../test/rendu'

afterEach(cleanup)
const fiche = (id: string, o: Partial<Parameters<typeof rendrePage>[1]> = {}) =>
  rendrePage(<ComptePage />, { chemin: `/console/comptes/${id}`, motif: '/console/comptes/:id', permissions: SUPER_ADMIN, ...o })
const bouton = (nom: string) => screen.getByRole('button', { name: nom })

describe('Fiche d’un compte : actes selon les permissions', () => {
  it('super administrateur : tous les actes ; lecteur : aucun ; propre compte : actes sur soi retirés', async () => {
    fiche('u-sna')
    expect(await screen.findByRole('heading', { level: 1, name: 'Rachel Biyong Mengue' })).toBeTruthy()
    // Cycle de vie dans la barre d'outils ; actes de sécurité dans l'onglet Sécurité ; sessions dans le leur.
    const barre = screen.getByRole('toolbar')
    for (const n of ['Modifier la fiche', 'Modifier les profils', 'Désactiver le compte', 'Supprimer le compte']) {
      expect(within(barre).getByRole('button', { name: n })).toBeTruthy()
    }
    fireEvent.click(screen.getByRole('tab', { name: 'Sécurité' }))
    const securite = screen.getByRole('group', { name: 'Actes de sécurité du compte' })
    for (const n of ['Exiger des actions', 'Réinitialiser le second facteur', 'Mot de passe provisoire']) {
      expect(within(securite).getByRole('button', { name: n })).toBeTruthy()
    }
    expect(screen.getByRole('tabpanel').textContent).toMatch(/vérifiée/)
    fireEvent.click(screen.getByRole('tab', { name: 'Sessions' }))
    expect(bouton('Fermer les sessions')).toBeTruthy()
    expect(screen.getByTestId('emplacement').textContent).toBe('/console/comptes/u-sna?onglet=sessions')
    fireEvent.click(screen.getByRole('tab', { name: 'Fiche' }))
    expect(screen.getByTestId('emplacement').textContent).toBe('/console/comptes/u-sna')
    cleanup()
    fiche('u-sna?onglet=securite', { permissions: LECTEUR })
    await screen.findByRole('heading', { level: 1, name: 'Rachel Biyong Mengue' })
    expect(screen.queryByRole('toolbar')?.querySelectorAll('button')).toHaveLength(0)
    expect(screen.getByRole('tab', { name: 'Sécurité' }).getAttribute('aria-selected')).toBe('true')
    expect(screen.queryByRole('group', { name: 'Actes de sécurité du compte' })).toBeNull()
    expect(screen.queryByRole('tab', { name: 'Journal' })).toBeNull()
    cleanup()
    fiche('u-super-admin?onglet=securite', { session: session(SUPER_ADMIN, { sujet: 'u-super-admin' }) })
    expect(await screen.findByText(/Vous consultez votre propre compte/)).toBeTruthy()
    expect(screen.queryByRole('button', { name: 'Modifier les profils' })).toBeNull()
    expect(screen.queryByRole('button', { name: 'Supprimer le compte' })).toBeNull()
    expect(screen.queryByRole('button', { name: 'Réinitialiser le second facteur' })).toBeNull()
    expect(bouton('Exiger des actions')).toBeTruthy()
  })

  it('onglets : fiche, sécurité, sessions, journal ; compte introuvable', async () => {
    fiche('u-premier-acces')
    expect(await screen.findByText('Opératrice production monétique')).toBeTruthy()
    fireEvent.click(screen.getByRole('tab', { name: 'Sécurité' }))
    expect(screen.getByText('Changer le mot de passe')).toBeTruthy()
    expect(screen.getByText('en attente')).toBeTruthy()
    fireEvent.click(screen.getByRole('tab', { name: 'Sessions' }))
    expect(await screen.findByText('Aucune session ouverte')).toBeTruthy()
    fireEvent.click(screen.getByRole('tab', { name: 'Journal' }))
    expect(await screen.findByText('Création du compte')).toBeTruthy()
    cleanup()
    fiche('u-chef-des')
    fireEvent.click(await screen.findByRole('tab', { name: 'Sessions' }))
    expect(await screen.findByText('10.20.3.41')).toBeTruthy()
    fireEvent.click(screen.getByRole('tab', { name: 'Sécurité' }))
    expect(screen.getByText('Aucune')).toBeTruthy()
    cleanup()
    fiche('inconnu')
    expect(await screen.findByText('Le chargement a échoué.')).toBeTruthy()
  })
})

describe('Actes sensibles : réauthentification FIDO2 (ADMIN_SENSITIVE)', () => {
  it('modifier les profils : choix, motif, clé de sécurité, profils à jour', async () => {
    const base = simules()
    const assertion = vi.fn(base.reauth.assertion)
    fiche('u-sna', { services: { ...base, reauth: { assertion } } })
    fireEvent.click(await screen.findByRole('button', { name: 'Modifier les profils' }))
    fireEvent.click(await screen.findByLabelText('Conformité'))
    fireEvent.click(bouton('Continuer vers la signature'))
    const d = await signer('Intérim de la conformité pendant trois mois')
    expect(await within(d).findByText('Signature confirmée')).toBeTruthy()
    expect(assertion).toHaveBeenCalledWith('ADMIN_SENSITIVE')
    fireEvent.click(within(d).getByRole('button', { name: 'Continuer' }))
    expect(await screen.findByText('Les profils du compte ont été modifiés.')).toBeTruthy()
    expect((await screen.findAllByText('Conformité')).length).toBeGreaterThan(0)
  })

  it('RSSI : les profils privilégiés ne sont jamais proposés et ceux détenus sont conservés', async () => {
    let recus: string[] = []
    const base = simules({ acteur: { id: 'u-rssi', nom: 'RSSI', permissions: RSSI } })
    fiche('u-super-admin', { permissions: RSSI, services: avec('comptes', { definirProfils: async (id, p) => { recus = p; return base.comptes.lire(id).then((c) => ({ ...c, profils: p })) } }, base) })
    fireEvent.click(await screen.findByRole('button', { name: 'Modifier les profils' }))
    await screen.findByLabelText('Conformité')
    expect(screen.queryByLabelText('Super administrateur')).toBeNull()
    fireEvent.click(screen.getByLabelText('Conformité'))
    fireEvent.click(bouton('Continuer vers la signature'))
    await signer()
    await waitFor(() => expect(recus).toEqual(['ROLE_CONFORMITE', 'ROLE_SUPER_ADMIN']))
  })

  it('428 : réauthentification exigée ; 403 IAM_REAUTH_INVALID ; annulation ; aucune clé : lien vers Mon compte', async () => {
    let erreur: unknown = new ApiError(428, 'IAM_REAUTH_REQUIRED', 'Réauthentification forte exigée', 'RQ-428')
    const base = simules()
    fiche('u-sna', { services: avec('comptes', { definirProfils: async () => { throw erreur } }, base) })
    fireEvent.click(await screen.findByRole('button', { name: 'Modifier les profils' }))
    fireEvent.click(await screen.findByLabelText('Conformité'))
    fireEvent.click(bouton('Continuer vers la signature'))
    const d = await signer()
    expect(await within(d).findByText('Cet acte exige une réauthentification avec votre clé de sécurité.')).toBeTruthy()
    expect(within(d).getByText('RQ-428')).toBeTruthy()
    erreur = new ApiError(403, 'IAM_REAUTH_INVALID', 'invalide', 'RQ-403')
    fireEvent.click(within(d).getByRole('button', { name: 'Réessayer' }))
    expect(await within(d).findByText(/a été refusée : recommencez/)).toBeTruthy()
    fireEvent.click(within(d).getByRole('button', { name: 'Annuler' }))
    cleanup()
    fiche('u-sna', { services: simules({ reauth: 'sansCle' }) })
    fireEvent.click(await screen.findByRole('button', { name: 'Modifier les profils' }))
    fireEvent.click(await screen.findByLabelText('Conformité'))
    fireEvent.click(bouton('Continuer vers la signature'))
    const d2 = await signer()
    expect(await within(d2).findByText(/Aucune clé de sécurité n'est enrôlée/)).toBeTruthy()
    expect(within(d2).getByRole('link', { name: 'Enrôler une clé dans « Mon compte »' }).getAttribute('href')).toBe('/console/mon-compte')
    cleanup()
    fiche('u-sna', { services: simules({ reauth: 'annulee' }) })
    fireEvent.click(await screen.findByRole('button', { name: 'Modifier les profils' }))
    fireEvent.click(await screen.findByLabelText('Conformité'))
    fireEvent.click(bouton('Continuer vers la signature'))
    const d3 = await signer()
    expect(await within(d3).findByText(/a été annulée : rien n'a été enregistré/)).toBeTruthy()
  })

  it('suppression : confirmation irréversible puis signature, retour à la liste', async () => {
    fiche('u-sna')
    fireEvent.click(await screen.findByRole('button', { name: 'Supprimer le compte' }))
    const c = await screen.findByRole('alertdialog')
    fireEvent.click(within(c).getByLabelText('Je confirme : cette action est irréversible.'))
    fireEvent.click(within(c).getByRole('button', { name: 'Continuer vers la signature' }))
    await signer('Compte créé en double par erreur')
    await waitFor(() => expect(screen.getByTestId('emplacement').textContent).toBe('/console/comptes'))
  })
})

describe('Actes motivés', () => {
  it('désactiver puis activer ; dernier super administrateur refusé', async () => {
    fiche('u-dg')
    fireEvent.click(await screen.findByRole('button', { name: 'Désactiver le compte' }))
    await confirmer('Désactiver le compte', 'Départ du collaborateur')
    expect(await screen.findByText('Le compte a été désactivé.')).toBeTruthy()
    fireEvent.click(await screen.findByRole('button', { name: 'Activer le compte' }))
    await confirmer('Activer le compte', 'Retour du collaborateur')
    expect(await screen.findByText('Le compte a été activé.')).toBeTruthy()
    cleanup()
    fiche('u-super-admin', { permissions: RSSI, services: simules({ acteur: { id: 'u-rssi', nom: 'RSSI', permissions: RSSI } }) })
    fireEvent.click(await screen.findByRole('button', { name: 'Désactiver le compte' }))
    await confirmer('Désactiver le compte', 'Tentative de désactivation')
    expect(await screen.findByText('La plateforme doit garder au moins un super administrateur actif.')).toBeTruthy()
  })

  it('exiger des actions : actions, courriel et motif', async () => {
    const base = simules()
    const exiger = vi.fn(base.comptes.exigerActions)
    fiche('u-dg?onglet=securite', { services: avec('comptes', { exigerActions: exiger }, base) })
    fireEvent.click(await screen.findByRole('button', { name: 'Exiger des actions' }))
    const d = await screen.findByRole('alertdialog')
    expect((within(d).getByRole('button', { name: 'Exiger des actions' }) as HTMLButtonElement).disabled).toBe(true)
    fireEvent.click(within(d).getByLabelText('Changer le mot de passe'))
    fireEvent.click(within(d).getByLabelText('Vérifier l’adresse électronique'))
    fireEvent.click(within(d).getByLabelText('Prévenir le titulaire par courriel'))
    fireEvent.change(within(d).getByLabelText(/Motif/), { target: { value: 'Suspicion de fuite de mot de passe' } })
    fireEvent.click(within(d).getByRole('button', { name: 'Exiger des actions' }))
    expect(await screen.findByText('Les actions ont été exigées.')).toBeTruthy()
    expect(exiger).toHaveBeenCalledWith('u-dg', ['MOT_DE_PASSE', 'VERIFIER_COURRIEL'], false, 'Suspicion de fuite de mot de passe')
    fireEvent.click(screen.getByRole('button', { name: 'Exiger des actions' }))
    fireEvent.click(within(await screen.findByRole('alertdialog')).getByRole('button', { name: 'Annuler' }))
    cleanup()
    fiche('u-dg?onglet=securite', { services: avec('comptes', { exigerActions: async () => { throw new ApiError(400, 'IAM_ACTIONS_REQUIRED', 'x', 'c') } }) })
    fireEvent.click(await screen.findByRole('button', { name: 'Exiger des actions' }))
    const d2 = await screen.findByRole('alertdialog')
    fireEvent.click(within(d2).getByLabelText('Configurer le second facteur'))
    fireEvent.change(within(d2).getByLabelText(/Motif/), { target: { value: 'Motif suffisamment long' } })
    fireEvent.click(within(d2).getByRole('button', { name: 'Exiger des actions' }))
    expect(await screen.findByText('Choisissez au moins une action.')).toBeTruthy()
  })

  it('second facteur, mot de passe provisoire affiché une fois, fermeture des sessions', async () => {
    fiche('u-dg?onglet=securite')
    fireEvent.click(await screen.findByRole('button', { name: 'Réinitialiser le second facteur' }))
    await confirmer('Réinitialiser le second facteur', 'Téléphone professionnel perdu')
    expect(await screen.findByText('Le second facteur a été réinitialisé.')).toBeTruthy()
    fireEvent.click(bouton('Mot de passe provisoire'))
    await confirmer('Mot de passe provisoire', 'Oubli du mot de passe signalé')
    expect(await screen.findByTestId('secret-valeur')).toBeTruthy()
    expect(screen.getByTestId('secret-valeur').textContent).toBe('Rt4!zW8q#Nc2Hv6e')
    fireEvent.click(within(screen.getByRole('dialog')).getAllByRole('button', { name: 'Fermer' }).at(-1)!)
    expect(screen.queryByTestId('secret-valeur')).toBeNull()
    fireEvent.click(screen.getByRole('tab', { name: 'Sessions' }))
    fireEvent.click(bouton('Fermer les sessions'))
    await confirmer('Fermer les sessions', 'Poste de travail volé')
    expect(await screen.findByText('Les sessions ont été fermées.')).toBeTruthy()
  })

  it('modifier la fiche : enregistrement, erreur de téléphone sur le champ, erreur générale', async () => {
    let code = 'IAM_PHONE_INVALID'
    const base = simules()
    let echec = false
    const { container } = fiche('u-dg', { services: avec('comptes', { modifier: async (id, f) => { if (echec) throw new ApiError(400, code, 'x', 'RQ-F'); return base.comptes.modifier(id, f) } }, base) })
    fireEvent.click(await screen.findByRole('button', { name: 'Modifier la fiche' }))
    const d = await screen.findByRole('dialog')
    fireEvent.change(container.querySelector('input[name="fonction"]')!, { target: { value: 'Directeur général adjoint chargé des opérations' } })
    fireEvent.change(container.querySelector('select[name="langue"]')!, { target: { value: 'en' } })
    fireEvent.click(within(d).getByRole('button', { name: 'Enregistrer la fiche' }))
    expect(await screen.findByText('La fiche du compte a été enregistrée.')).toBeTruthy()
    expect(await screen.findByText('Directeur général adjoint chargé des opérations')).toBeTruthy()
    echec = true
    fireEvent.click(bouton('Modifier la fiche'))
    const d2 = await screen.findByRole('dialog')
    fireEvent.click(within(d2).getByRole('button', { name: 'Enregistrer la fiche' }))
    expect(await within(d2).findByText(/Numéro de téléphone invalide/)).toBeTruthy()
    code = 'IAM_IDP_UNAVAILABLE'
    fireEvent.click(within(d2).getByRole('button', { name: 'Enregistrer la fiche' }))
    expect(await within(d2).findByText('RQ-F')).toBeTruthy()
    fireEvent.click(within(d2).getByRole('button', { name: 'Annuler' }))
    expect(screen.queryByRole('dialog')).toBeNull()
  })
})
