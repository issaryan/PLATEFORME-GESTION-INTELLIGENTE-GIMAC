import { ADRESSES, expect, test } from '../fixtures'
import { confirmer, naviguer, signer, signerEtTerminer } from './outils'
import { Passerelle, PERMISSIONS_SUPER_ADMIN } from './passerelle'

// Fonctionnalité : chaque acte d'administration de la console atteint la route attendue de la passerelle
// (VITE_SERVICES=http), avec son motif ; l'annulation de la clé de sécurité n'envoie aucune requête d'effet.

test.describe('Fonctionnalité : administration par la passerelle', () => {
  test('Scénario : créer puis administrer un compte', async ({ page, context }) => {
    await context.grantPermissions(['clipboard-read', 'clipboard-write'])
    const gw = new Passerelle({ session: { permissions: PERMISSIONS_SUPER_ADMIN } })
    await gw.brancher(page)
    await page.goto(`${ADRESSES.consoleHttp}/console/comptes/nouveau`)
    await page.locator('input[name="identifiant"]').fill('rssi')
    await page.locator('input[name="email"]').fill('rssi.bis@gimac-afr.org')
    await page.locator('input[name="prenom"]').fill('Paul')
    await page.locator('input[name="nom"]').fill('Owono')
    await page.getByLabel('Normes et agréments').check()
    await page.getByLabel('Définir un mot de passe provisoire').check()
    await page.getByRole('button', { name: 'Créer le compte' }).click()
    await expect(page.getByText('Identifiant ou courriel déjà utilisé.')).toBeVisible()
    await page.locator('input[name="identifiant"]').fill('p.owono')
    await page.getByRole('button', { name: 'Créer le compte' }).click()
    await expect(page.getByTestId('secret-valeur')).toHaveText('Hn5#Wd2!Qs8vKp4z')
    expect(gw.appels.filter((a) => a.methode === 'POST' && a.chemin === '/bff/console/iam/comptes').at(-1)!.corps).toMatchObject({ identifiant: 'p.owono', envoyerInvitation: false, motDePasseProvisoire: true })
    await page.getByRole('button', { name: 'Ouvrir la fiche du compte' }).click()
    await expect(page.getByRole('heading', { level: 1 })).toHaveText('Paul Owono')

    await page.getByRole('button', { name: 'Désactiver le compte' }).click()
    await confirmer(page, 'Désactiver le compte', 'Compte en attente de validation RH')
    await expect(page.getByText('Le compte a été désactivé.')).toBeVisible()
    await page.getByRole('button', { name: 'Activer le compte' }).click()
    await confirmer(page, 'Activer le compte', 'Validation RH reçue ce jour')
    await expect(page.getByText('Le compte a été activé.')).toBeVisible()
    await page.getByRole('tab', { name: 'Sécurité' }).click()
    await page.getByRole('button', { name: 'Exiger des actions' }).click()
    await page.getByRole('alertdialog').getByLabel('Changer le mot de passe').check()
    await page.getByRole('alertdialog').getByLabel(/Motif/).fill('Mot de passe communiqué par erreur')
    await page.getByRole('alertdialog').getByRole('button', { name: 'Exiger des actions' }).click()
    await expect(page.getByText('Les actions ont été exigées.')).toBeVisible()
    await page.getByRole('button', { name: 'Réinitialiser le second facteur' }).click()
    await confirmer(page, 'Réinitialiser le second facteur', 'Téléphone professionnel perdu')
    await expect(page.getByText('Le second facteur a été réinitialisé.')).toBeVisible()
    await page.getByRole('button', { name: 'Mot de passe provisoire' }).click()
    await confirmer(page, 'Mot de passe provisoire', 'Nouveau mot de passe demandé au support')
    await expect(page.getByTestId('secret-valeur')).toHaveText('Zq8#Lm3!Vt6pWx2r')
    await page.getByRole('dialog').getByRole('button', { name: 'Copier' }).click()
    await expect(page.getByTestId('secret-copie')).toHaveText('Copié dans le presse-papiers.')
    await page.getByRole('dialog').getByRole('button', { name: 'Fermer' }).last().click()
    await page.getByRole('tab', { name: 'Sessions' }).click()
    await page.getByRole('button', { name: 'Fermer les sessions' }).click()
    await confirmer(page, 'Fermer les sessions', 'Sessions ouvertes sur un poste partagé')
    await expect(page.getByText('Les sessions ont été fermées.')).toBeVisible()
    await page.getByRole('button', { name: 'Modifier la fiche' }).click()
    await page.getByRole('dialog').locator('input[name="telephone"]').fill('+237 677 00 00 01')
    await page.getByRole('button', { name: 'Enregistrer la fiche' }).click()
    await expect(page.getByText('La fiche du compte a été enregistrée.')).toBeVisible()
    for (const [route, motif] of [['/activation', 'Validation RH reçue ce jour'], ['/actions-requises', 'Mot de passe communiqué par erreur'], ['/sessions/fermeture', 'Sessions ouvertes sur un poste partagé']]) {
      expect(gw.appels.find((a) => a.chemin === `/bff/console/iam/comptes/u-p.owono${route}`)!.corps).toMatchObject({ motif })
    }
  })

  test('Scénario : journal, messagerie, profils, configuration et journalisation par la passerelle', async ({ page }) => {
    const gw = new Passerelle({ session: { permissions: PERMISSIONS_SUPER_ADMIN } })
    await gw.brancher(page)
    await page.goto(`${ADRESSES.consoleHttp}/console/journal`)
    await expect(page.getByRole('cell', { name: 'Modification des profils' })).toBeVisible()
    await page.getByRole('combobox', { name: 'Compte concerné' }).selectOption('u-sna')
    await expect.poll(() => gw.appels.some((a) => a.chemin === '/bff/console/iam/comptes/journal' && a.recherche.includes('compte=u-sna'))).toBe(true)

    await naviguer(page, 'Messagerie')
    await expect(page.getByText('mot de passe non défini')).toBeVisible()
    await page.getByRole('button', { name: 'Modifier la messagerie' }).click()
    await page.locator('input[name="motDePasse"]').fill('Secret-SMTP-2026')
    await page.getByLabel(/Motif/).fill('Première configuration du relais SMTP')
    await page.getByRole('button', { name: 'Enregistrer la messagerie' }).click()
    await expect(page.getByText('La messagerie a été enregistrée.')).toBeVisible()
    await page.getByRole('button', { name: 'Envoyer un courriel de test' }).click()
    await page.locator('input[name="destinataire"]').fill('super.admin@gimac-afr.org')
    await page.getByRole('dialog').getByRole('button', { name: 'Envoyer un courriel de test' }).click()
    await expect(page.getByText('Courriel de test envoyé à super.admin@gimac-afr.org.')).toBeVisible()

    await naviguer(page, 'Profils et permissions')
    await page.getByRole('button', { name: 'Modifier la composition' }).click()
    await page.getByRole('dialog').getByLabel('HOM_REPLAY_ADMIN').check()
    await page.getByRole('button', { name: 'Continuer vers la signature' }).click()
    await signerEtTerminer(page, 'Rejeu confié au service Normes et Agréments')
    expect(gw.appels.find((a) => a.chemin === '/bff/console/iam/configuration/profils/ROLE_SNA/permissions')!.corps).toEqual({ permissions: ['HOM_EVIDENCE_SUBMIT', 'HOM_REPLAY_ADMIN'], motif: 'Rejeu confié au service Normes et Agréments' })

    await naviguer(page, 'Configuration')
    await expect(page.getByText('******')).toBeVisible()
    await naviguer(page, 'Journalisation')
    await page.getByRole('combobox', { name: 'Service' }).selectOption('iam')
    await page.getByRole('row', { name: /ROOT/ }).getByRole('button', { name: 'Modifier le niveau' }).click()
    await page.getByRole('dialog').getByRole('combobox', { name: 'Nouveau niveau' }).selectOption('WARN')
    await page.getByRole('dialog').getByLabel(/Motif/).fill('Réduction du volume de journaux')
    await page.getByRole('button', { name: 'Appliquer le niveau' }).click()
    await expect(page.getByText('Niveau WARN appliqué à ROOT.')).toBeVisible()
  })

  test('Scénario : l’utilisateur annule la demande de sa clé de sécurité', async ({ page }) => {
    const gw = new Passerelle({ session: { permissions: PERMISSIONS_SUPER_ADMIN } })
    await gw.brancher(page)
    await page.goto(`${ADRESSES.consoleHttp}/console/comptes/u-sna`)
    await page.evaluate(() => { (window as unknown as { __gmCleAnnulee: boolean }).__gmCleAnnulee = true })
    await page.getByRole('button', { name: 'Modifier les profils' }).click()
    await page.getByRole('button', { name: 'Continuer vers la signature' }).click()
    const d = await signer(page, 'Revue annuelle des habilitations')
    await expect(d.getByText("La demande de votre clé de sécurité a été annulée : rien n'a été enregistré.")).toBeVisible()
    expect(gw.appels.some((a) => a.chemin.endsWith('/profils') && a.methode === 'PUT')).toBe(false)
    await d.getByRole('button', { name: 'Annuler' }).click()
    await naviguer(page, 'Mon compte')
    await page.getByRole('button', { name: 'Enrôler une clé' }).click()
    await page.getByRole('dialog').locator('input[name="nomNouvelleCle"]').fill('Clé refusée')
    await page.getByRole('dialog').getByRole('button', { name: 'Enrôler une clé' }).click()
    await expect(page.getByText("La demande de votre clé de sécurité a été annulée : rien n'a été enregistré.")).toBeVisible()
    expect(gw.appels.some((a) => a.methode === 'POST' && a.chemin === '/bff/console/iam/moi/cles-securite')).toBe(false)
  })

  test('Scénario : passerelle indisponible au chargement de la session', async ({ page }) => {
    const gw = new Passerelle({ sessionIndisponible: true })
    await gw.brancher(page)
    await page.goto(`${ADRESSES.consoleHttp}/console/tableau-de-bord`)
    await expect(page.getByText(/La session n'a pas pu être chargée/)).toBeVisible()
  })
})
