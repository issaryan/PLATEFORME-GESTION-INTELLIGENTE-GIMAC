// Fonctionnalité : « Mon activité » (D-76, docs/lot1/mon-activite.md §6), services simulés. Un collaborateur
// tient sa journée (activités ajoutées, statut, ordre, report, suppression), rédige son rapport prérempli et le
// soumet à son responsable, tient son agenda (invitation, événement avec participants, journée entière) et ses
// tâches ; un responsable de service suit son équipe, lit la journée et l'agenda d'un membre, vise un rapport
// reçu (document en aperçu) et confie une tâche ; l'administration tient le catalogue des unités et rattache
// un compte. Captures en thème clair et sombre.

const CAPTURES = process.env.GIMAC_CAPTURES
async function capturer(page: Page, nom: string) {
  if (!CAPTURES) return
  mkdirSync(CAPTURES, { recursive: true })
  await page.screenshot({ path: join(CAPTURES, `${nom}.png`), fullPage: true })
}
const suffixe = (theme: 'light' | 'dark') => (theme === 'light' ? 'clair' : 'sombre')
