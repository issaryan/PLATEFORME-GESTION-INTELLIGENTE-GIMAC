import { ADRESSES, demo, expect, test } from '../fixtures'
import { confirmer, naviguer, ongletSelectionne, signer, signerEtTerminer } from './outils'

// Fonctionnalité : le super administrateur configure la plateforme depuis la console, sans ouvrir la
// console du fournisseur d'identité (D-62). Services simulés (VITE_SERVICES absent).

test.describe('Fonctionnalité : console du super administrateur', () => {
  test.beforeEach(async ({ page, context }) => {
    await context.grantPermissions(['clipboard-read', 'clipboard-write'])
    await demo(page, { profil: 'ROLE_SUPER_ADMIN', theme: 'light' })
  })

  test('Scénario : suivre l’état de la plateforme en temps réel', async ({ page }) => {
    await test.step('Étant donné le super administrateur connecté à la console', async () => {
      await page.goto(`${ADRESSES.console}/`)
    })
    await test.step('Alors son tableau de bord montre l’état global, les services, les serveurs et les alertes', async () => {
      await expect(page.getByRole('heading', { level: 1 })).toHaveText('Tableau de bord du super administrateur')
      const direct = page.getByRole('region', { name: 'État en temps réel' })
      await expect(direct.getByRole('status')).toHaveText('Temps réel')
      await expect(direct.getByText('7 / 8')).toBeVisible()
      await expect(page.getByRole('cell', { name: 'notification', exact: true })).toBeVisible()
      await expect(page.getByRole('cell', { name: 'gimac-donnees-01', exact: true })).toBeVisible()
      await expect(page.getByRole('cell', { name: 'ServiceInjoignable' })).toBeVisible()
      await expect(page.getByRole('group', { name: 'Comptes de la plateforme' })).toBeVisible()
      await expect(page.locator('.gm-footer')).toBeVisible()
    })
    await test.step('Quand il passe l’interface en anglais', async () => {
      await page.getByRole('button', { name: /Langue/ }).click()
      await page.getByRole('combobox', { name: 'Langue' }).selectOption('en')
    })
    await test.step('Alors les libellés sont traduits', async () => {
      await expect(page.getByRole('heading', { level: 1 })).toHaveText('Super administrator dashboard')
      await page.getByRole('combobox', { name: 'Language' }).selectOption('fr')
    })
  })

  test('Scénario : créer un compte avec mot de passe provisoire puis l’administrer', async ({ page }) => {
    await page.goto(`${ADRESSES.console}/console/comptes`)
    await test.step('Quand il crée le compte d’une nouvelle analyste avec un mot de passe provisoire', async () => {
      await page.getByRole('button', { name: 'Créer un compte' }).click()
      await page.locator('input[name="identifiant"]').fill('n.mvondo')
      await page.locator('input[name="email"]').fill('n.mvondo@gimac-afr.org')
      await page.locator('input[name="prenom"]').fill('Nadège')
      await page.locator('input[name="nom"]').fill('Mvondo')
      await page.locator('input[name="telephone"]').fill('+237 699 45 67 89')
      await page.getByLabel('Normes et agréments').check()
      await page.getByLabel('Les deux').check()
      await page.getByRole('button', { name: 'Créer le compte' }).click()
    })
    await test.step('Alors le mot de passe provisoire est affiché une seule fois, avec copie', async () => {
      await expect(page.getByText('Compte n.mvondo créé')).toBeVisible()
      await expect(page.getByTestId('secret-valeur')).toHaveText('Kp7#vQ2m!Lx9Tz4w')
      await page.getByRole('button', { name: 'Copier' }).click()
      await expect(page.getByTestId('secret-copie')).toHaveText('Copié dans le presse-papiers.')
      await page.getByRole('button', { name: 'Ouvrir la fiche du compte' }).click()
      await expect(page.getByRole('heading', { level: 1 })).toHaveText('Nadège Mvondo')
    })
    await test.step('Quand il change ses profils avec sa clé de sécurité', async () => {
      await page.getByRole('button', { name: 'Modifier les profils' }).click()
      await page.getByRole('dialog').getByLabel('Conformité').check()
      await page.getByRole('button', { name: 'Continuer vers la signature' }).click()
      await signerEtTerminer(page, 'Renfort temporaire de la conformité')
      await expect(page.getByText('Les profils du compte ont été modifiés.')).toBeVisible()
    })
    await test.step('Et il exige des actions, réinitialise le second facteur, définit un mot de passe provisoire, ferme les sessions', async () => {
      await page.getByRole('tab', { name: 'Sécurité' }).click()
      await page.getByRole('button', { name: 'Exiger des actions' }).click()
      const d = page.getByRole('alertdialog')
      await d.getByLabel('Vérifier l’adresse électronique').check()
      await d.getByLabel(/Motif/).fill('Adresse électronique à confirmer')
      await d.getByRole('button', { name: 'Exiger des actions' }).click()
      await expect(page.getByText('Les actions ont été exigées.')).toBeVisible()
      await page.getByRole('button', { name: 'Réinitialiser le second facteur' }).click()
      await confirmer(page, 'Réinitialiser le second facteur', 'Téléphone professionnel remplacé')
      await expect(page.getByText('Le second facteur a été réinitialisé.')).toBeVisible()
      await page.getByRole('button', { name: 'Mot de passe provisoire' }).click()
      await confirmer(page, 'Mot de passe provisoire', 'Mot de passe oublié par la titulaire')
      await expect(page.getByTestId('secret-valeur')).toHaveText('Rt4!zW8q#Nc2Hv6e')
      await page.getByRole('dialog').getByRole('button', { name: 'Fermer' }).last().click()
      await page.getByRole('tab', { name: 'Sessions' }).click()
      await page.getByRole('button', { name: 'Fermer les sessions' }).click()
      await confirmer(page, 'Fermer les sessions', 'Session suspecte hors des heures ouvrées')
      await expect(page.getByText('Les sessions ont été fermées.')).toBeVisible()
    })
    await test.step('Et il modifie la fiche, désactive puis réactive le compte', async () => {
      await page.getByRole('button', { name: 'Modifier la fiche' }).click()
      await page.getByRole('dialog').locator('input[name="fonction"]').fill('Analyste Normes et Agréments')
      await page.getByRole('button', { name: 'Enregistrer la fiche' }).click()
      await expect(page.getByText('La fiche du compte a été enregistrée.')).toBeVisible()
      await page.getByRole('button', { name: 'Désactiver le compte' }).click()
      await confirmer(page, 'Désactiver le compte', 'Suspension pendant l’enquête interne')
      await expect(page.getByText('Le compte a été désactivé.')).toBeVisible()
      await page.getByRole('button', { name: 'Activer le compte' }).click()
      await confirmer(page, 'Activer le compte', 'Fin de l’enquête interne')
      await expect(page.getByText('Le compte a été activé.')).toBeVisible()
    })
    await test.step('Alors la sécurité, les sessions et le journal du compte sont consultables', async () => {
      await page.getByRole('tab', { name: 'Sécurité' }).click()
      await expect(page.getByText('Vérifier l’adresse électronique')).toBeVisible()
      await page.getByRole('tab', { name: 'Sessions' }).click()
      await expect(page.getByText('Aucune session ouverte')).toBeVisible()
      await page.getByRole('tab', { name: 'Journal' }).click()
      await expect(page.getByRole('cell', { name: 'Création du compte' })).toBeVisible()
    })
    await test.step('Quand il supprime le compte (confirmation irréversible puis signature)', async () => {
      await page.getByRole('button', { name: 'Supprimer le compte' }).click()
      await page.getByRole('alertdialog').getByLabel('Je confirme : cette action est irréversible.').check()
      await page.getByRole('button', { name: 'Continuer vers la signature' }).click()
      await signer(page, 'Compte créé pour une mission annulée')
      await expect(page.getByRole('heading', { level: 1 })).toHaveText('Comptes')
    })
  })

  test('Scénario : rechercher et filtrer les comptes', async ({ page }) => {
    await page.goto(`${ADRESSES.console}/console/comptes`)
    await expect(page.getByText('14 compte(s)')).toBeVisible()
    await page.getByRole('searchbox', { name: 'Rechercher', exact: true }).fill('ndong')
    await expect(page.getByRole('link', { name: 'c.ndong' })).toBeVisible()
    await page.getByRole('button', { name: 'Réinitialiser' }).click()
    await page.getByRole('combobox', { name: 'État' }).selectOption('SANS_2FA')
    await expect(page.getByText('2 compte(s)')).toBeVisible()
    await page.getByRole('combobox', { name: 'Profil' }).selectOption('ROLE_RSSI')
    await expect(page.getByText('Aucun compte ne correspond')).toBeVisible()
    await page.getByRole('button', { name: 'Réinitialiser' }).click()
    await page.getByRole('combobox', { name: 'Taille de page' }).selectOption('50')
    await page.getByRole('link', { name: 'super.admin' }).click()
    await expect(page.getByText(/Vous consultez votre propre compte/)).toBeVisible()
    await expect(page.getByRole('button', { name: 'Supprimer le compte' })).toHaveCount(0)
  })

  test('Scénario : appliquer la politique de sécurité, refus du service champ par champ', async ({ page }) => {
    await page.goto(`${ADRESSES.console}/console/politique-securite`)
    await page.getByRole('button', { name: 'Modifier la politique' }).click()
    await page.locator('input[name="longueurMinimale"]').fill('8')
    await page.locator('input[name="otpPeriodeSecondes"]').fill('90')
    await page.getByRole('button', { name: 'Appliquer la politique' }).click()
    await signer(page, 'Essai d’une politique trop faible')
    await expect(page.getByText('Politique de sécurité refusée : corrigez les champs signalés.')).toBeVisible()
    await expect(page.getByText('Valeur refusée par MS-IAM : 12 à 128.')).toBeVisible()
    await expect(page.getByText('Valeur refusée par MS-IAM : 30 à 60.')).toBeVisible()
    await page.locator('input[name="longueurMinimale"]').fill('16')
    await page.locator('input[name="otpPeriodeSecondes"]').fill('30')
    await page.locator('select[name="otpAlgorithme"]').selectOption('HmacSHA512')
    await page.getByRole('button', { name: 'Appliquer la politique' }).click()
    await signerEtTerminer(page, 'Alignement sur la PSSI révisée')
    await expect(page.getByText('La politique de sécurité a été appliquée.')).toBeVisible()
    await expect(page.locator('.gm-card').filter({ hasText: 'Mots de passe' }).getByText('16', { exact: true })).toBeVisible()
  })

  test('Scénario : configurer la messagerie et envoyer un courriel de test', async ({ page }) => {
    await page.goto(`${ADRESSES.console}/console/plateforme/courriels`)
    await expect(page.getByText('mot de passe défini')).toBeVisible()
    await page.getByRole('button', { name: 'Modifier la messagerie' }).click()
    await expect(page.locator('input[name="motDePasse"]')).toHaveAttribute('type', 'password')
    await page.locator('input[name="port"]').fill('465')
    await page.getByLabel('SSL/TLS implicite').check()
    await page.locator('input[name="motDePasse"]').fill('N0uveau-Secret-SMTP')
    await page.getByLabel(/Motif/).fill('Migration vers le relais SMTP sécurisé')
    await page.getByRole('button', { name: 'Enregistrer la messagerie' }).click()
    await expect(page.getByText('La messagerie a été enregistrée.')).toBeVisible()
    await page.getByRole('button', { name: 'Envoyer un courriel de test' }).click()
    await page.locator('input[name="destinataire"]').fill('rssi@gimac-afr.org')
    await page.getByRole('dialog').getByRole('button', { name: 'Envoyer un courriel de test' }).click()
    await expect(page.getByText('Courriel de test envoyé à rssi@gimac-afr.org.')).toBeVisible()
  })

  test('Scénario : recomposer un profil par domaine de permissions', async ({ page }) => {
    await page.goto(`${ADRESSES.console}/console/profils`)
    await page.getByRole('row', { name: /ROLE_SNA/ }).getByRole('button', { name: 'Modifier la composition' }).click()
    const d = page.getByRole('dialog')
    await ongletSelectionne(d, 'Droits')
    await expect(d.getByText('Homologation (HOM)')).toBeVisible()
    await expect(d.getByText(/INTERNAL_/)).toHaveCount(0)
    await d.getByLabel('HOM_REPLAY_ADMIN').check()
    await d.getByRole('button', { name: 'Continuer vers la signature' }).click()
    await signerEtTerminer(page, 'Rejeu confié au service Normes et Agréments')
    await expect(page.getByText(/La composition du profil Normes et Agréments a été enregistrée/)).toBeVisible()
  })

  test('Scénario : consulter la configuration et changer un niveau de journalisation', async ({ page }) => {
    await page.goto(`${ADRESSES.console}/console/plateforme/configuration`)
    await expect(page.getByText('bff-console-iam')).toBeVisible()
    await expect(page.getByText('******')).toBeVisible()
    await page.getByRole('link', { name: 'Niveaux de journalisation' }).first().click()
    await expect(page.getByText('cm.gimac.des.iam.web')).toBeVisible()
    await page.getByRole('searchbox', { name: 'Filtrer par préfixe de logger' }).fill('org.')
    await expect(page.getByText('cm.gimac.des.iam.web')).toHaveCount(0)
    await page.getByRole('row', { name: /org\.hibernate\.SQL/ }).getByRole('button', { name: 'Modifier le niveau' }).click()
    await page.getByRole('dialog').getByRole('combobox', { name: 'Nouveau niveau' }).selectOption('DEBUG')
    await page.getByRole('dialog').getByLabel(/Motif/).fill('Analyse des lenteurs SQL')
    await page.getByRole('button', { name: 'Appliquer le niveau' }).click()
    await expect(page.getByText('Niveau DEBUG appliqué à org.hibernate.SQL.')).toBeVisible()
  })

  test('Scénario : consulter le journal d’administration filtré par compte', async ({ page }) => {
    await page.goto(`${ADRESSES.console}/console/tableau-de-bord`)
    await naviguer(page, 'Journal d’administration')
    await expect(page.getByRole('cell', { name: 'Création du compte' })).toBeVisible()
    await page.getByRole('combobox', { name: 'Compte concerné' }).selectOption('u-inactif')
    await expect(page.getByRole('cell', { name: 'Désactivation' })).toBeVisible()
    await expect(page.getByRole('cell', { name: 'Création du compte' })).toHaveCount(0)
  })

  test('Scénario : gérer son propre compte (Mon compte)', async ({ page }) => {
    await page.goto(`${ADRESSES.console}/console/tableau-de-bord`)
    await naviguer(page, 'Mon compte')
    await expect(page.getByRole('heading', { level: 1, name: 'Mon compte' })).toBeVisible()
    await page.getByRole('button', { name: 'Modifier ma fiche' }).click()
    await page.getByRole('dialog').locator('input[name="fonction"]').fill('Super administrateur de la plateforme DES')
    await page.getByRole('dialog').getByRole('button', { name: 'Enregistrer ma fiche' }).click()
    await expect(page.getByText('Votre fiche a été enregistrée.')).toBeVisible()
    await page.getByRole('button', { name: 'Enrôler une clé' }).click()
    await page.getByRole('dialog').locator('input[name="nomNouvelleCle"]').fill('Clé de secours (coffre)')
    await page.getByRole('dialog').getByRole('button', { name: 'Enrôler une clé' }).click()
    await expect(page.getByText('La clé « Clé de secours (coffre) » est enrôlée.')).toBeVisible()
    await page.getByRole('row', { name: /YubiKey 5 NFC/ }).getByRole('button', { name: 'Supprimer la clé' }).click()
    await page.getByRole('alertdialog').getByLabel('Je confirme : cette action est irréversible.').check()
    await confirmer(page, 'Supprimer la clé')
    await expect(page.getByText('La clé « YubiKey 5 NFC (bureau) » a été supprimée.')).toBeVisible()
    await page.getByRole('row', { name: /Firefox 131/ }).getByRole('button', { name: 'Fermer la session' }).click()
    await confirmer(page, 'Fermer la session')
    await expect(page.getByText('La session a été fermée : l’appareil est déconnecté.')).toBeVisible()
    await page.getByRole('button', { name: 'Changer mon mot de passe' }).click()
    const mdp = page.getByRole('dialog')
    await mdp.locator('input[name="motDePasseActuel"]').fill('Gimac-Demo-2026!')
    await mdp.locator('input[name="nouveauMotDePasse"]').fill('Nouveau-Secret-2026!')
    await mdp.locator('input[name="confirmationMotDePasse"]').fill('Nouveau-Secret-2026!')
    await mdp.getByRole('button', { name: 'Enregistrer le mot de passe' }).click()
    await expect(page.getByText('Votre mot de passe a été changé.')).toBeVisible()
    await page.getByRole('button', { name: 'Reconfigurer mon code TOTP' }).click()
    await expect(page.getByRole('dialog').getByRole('img', { name: /Code QR/ })).toBeVisible()
    await page.getByRole('dialog').locator('input[name="codeTotp"]').fill('246810')
    await page.getByRole('dialog').getByRole('button', { name: 'Vérifier et activer' }).click()
    await expect(page.getByText(/Votre application d’authentification est associée/)).toBeVisible()
    await page.getByRole('button', { name: 'Fermer les autres sessions' }).click()
    await confirmer(page, 'Fermer les autres sessions')
    await expect(page.getByText('Vos autres sessions ont été fermées. Cet appareil reste connecté.')).toBeVisible()
  })
})
